// chain-size.mjs -- the copyLast inlining-chain gate (M1 SLIM2, ruling Q-M1-GATE A). Tier: DETERMINISTIC
// (bytecode lengths on a pinned engine), gated in `npm test` by test/chainsize.test.js.
//
// V8 inlines a callee only while the callee plus its already-inlined callees fit the cumulative-inlining
// reserve (920 / 1.2 = 767 B of bytecode). copyLast's chain is copyLast + lastCheck + rotCopy; at 766 B or
// less it inlines into a caller that inlines copyTo (whose chain copyTo + copyCheck + rotCopy is the anchor).
// One byte over and copyLast is CALLED again with no behaviour change to warn anyone, so this fails closed.
//
//   node test/tools/chain-size.mjs --target <abs path to a RingBuffer.js>
//
// Prints one JSON line (the verdict) and exits 0 when ok, 1 on any failure (bad usage included).
// ok only when: the child and the parent engine both equal PIN (any other Node / V8 FAILS until re-pinned);
// copyLast, lastCheck, rotCopy, copyTo and copyCheck each appear in EXACTLY one dump block with a positive
// integer length; copyLast + lastCheck + rotCopy <= CHAIN_MAX; the child printed CHAIN-DONE.
//
// The dump is the stdout of a fresh child every call (never a file):
//   process.execPath --print-bytecode --no-flush-bytecode chain-size.mjs --child <target>
// The child imports the target, runs copyTo and copyLast(d, 0, 64) on a full 64-ring (so rotCopy compiles),
// and prints `CHAIN-ENGINE {node, v8}` then `CHAIN-DONE`. A block starts at a line matching HEADER; its length
// is the first `Bytecode length: N` line inside that block only. Names match exactly, so copyLast never
// matches copyLastFast. Test tooling only: not shipped.
import { execFileSync } from 'node:child_process';
import { isAbsolute } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const PIN = Object.freeze({ node: 'v26.8.2', v8: '14.6.202.34-node.28' });
export const CHAIN_MAX = 766;
export const CHAIN = Object.freeze(['copyLast', 'lastCheck', 'rotCopy']);
export const ANCHOR = Object.freeze(['copyTo', 'copyCheck', 'rotCopy']);
export const NAMES = Object.freeze(['copyLast', 'lastCheck', 'rotCopy', 'copyTo', 'copyCheck']);

const HEADER = /^\[generated bytecode for function: (\S+) \(0x[0-9a-f]+ <SharedFunctionInfo[^>]*>\)\]$/;
const LENGTH = /^Bytecode length: (\d+)$/;
const ENGINE = /^CHAIN-ENGINE (\{.*\})$/;
const SELF = fileURLToPath(import.meta.url);

/**
 * Parse a `--print-bytecode` dump. Returns { fns: { name: { blocks, len } } for every NAMES entry (len is the
 * first block's own length, null when it has none), engine: { node, v8 } or null, done }.
 */
export function parseDump(txt) {
    const blocks = [];
    let cur = null;
    let engine = null;
    let engines = 0;
    let done = false;
    for (const ln of String(txt).split('\n')) {
        const h = HEADER.exec(ln);
        if (h) { cur = { name: h[1], len: null }; blocks.push(cur); continue; }
        if (ln === 'CHAIN-DONE') { done = true; continue; }
        const e = ENGINE.exec(ln);
        if (e) {
            engines++;
            try { engine = JSON.parse(e[1]); } catch { engine = null; }
            continue;
        }
        if (cur !== null && cur.len === null) {
            const L = LENGTH.exec(ln);
            if (L) cur.len = Number(L[1]);
        }
    }
    const fns = {};
    for (const n of NAMES) {
        const bs = blocks.filter((b) => b.name === n);
        fns[n] = { blocks: bs.length, len: bs.length > 0 ? bs[0].len : null };
    }
    return { fns, engine: engines === 1 ? engine : null, engines, done };
}

/** Run a fresh child on absTarget and parse its stdout. A child that fails returns { error } and no blocks. */
export function readChain(absTarget) {
    if (typeof absTarget !== 'string' || !isAbsolute(absTarget)) {
        return { ...parseDump(''), error: 'target must be an absolute path (got ' + String(absTarget) + ')' };
    }
    let txt;
    try {
        txt = execFileSync(process.execPath, ['--print-bytecode', '--no-flush-bytecode', SELF, '--child', absTarget],
            { encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'pipe'] });
    } catch (err) {
        return { ...parseDump(''), error: 'child failed: ' + String(err && err.message).split('\n')[0] };
    }
    return parseDump(txt);
}

function sameEngine(e, pin) {
    return e !== null && typeof e === 'object' && e.node === pin.node && e.v8 === pin.v8;
}

function sum(fns, names) {
    let s = 0;
    for (const n of names) s += fns[n].len;
    return s;
}

/**
 * Decide on a parsed dump. opts.parent (default: this process's engine) and opts.pin (default PIN) exist so the
 * test can show a one-field mismatch failing. NaN-safe: every test is written so a NaN / null fails it.
 */
export function verdict(parsed, opts = {}) {
    const parent = opts.parent || { node: process.version, v8: process.versions.v8 };
    const pin = opts.pin || PIN;
    const reasons = [];
    if (parsed.error) reasons.push(parsed.error);
    if (!sameEngine(parsed.engine, pin)) {
        reasons.push('child engine ' + JSON.stringify(parsed.engine) + ' is not the pin ' + JSON.stringify(pin));
    }
    if (!sameEngine(parent, pin)) {
        reasons.push('parent engine ' + JSON.stringify(parent) + ' is not the pin ' + JSON.stringify(pin));
    }
    const fns = {};
    let lensOk = true;
    for (const n of NAMES) {
        const f = parsed.fns[n];
        fns[n] = f.len;
        if (f.blocks !== 1) { reasons.push(n + ' in ' + f.blocks + ' blocks (want exactly 1)'); lensOk = false; }
        else if (!(Number.isInteger(f.len) && f.len > 0)) { reasons.push(n + ' has no positive length'); lensOk = false; }
    }
    const chain = lensOk ? sum(parsed.fns, CHAIN) : NaN;
    const chainCopyTo = lensOk ? sum(parsed.fns, ANCHOR) : NaN;
    if (lensOk && !(chain <= CHAIN_MAX)) reasons.push('chain ' + chain + ' > ' + CHAIN_MAX);
    if (parsed.done !== true) reasons.push('no CHAIN-DONE marker');
    return {
        ok: reasons.length === 0,
        chain: Number.isNaN(chain) ? null : chain,
        chainCopyTo: Number.isNaN(chainCopyTo) ? null : chainCopyTo,
        max: CHAIN_MAX,
        fns,
        engine: { child: parsed.engine, parent, pin },
        reasons,
    };
}

async function child(target) {
    const { RingBuffer } = await import(pathToFileURL(target).href);
    const rb = new RingBuffer(64);
    for (let i = 0; i < 64; i++) rb.push(i + 0.5);
    const d = new Float32Array(64);
    rb.copyTo(d, 0);
    rb.copyLast(d, 0, 64);
    process.stdout.write('\nCHAIN-ENGINE ' + JSON.stringify({ node: process.version, v8: process.versions.v8 }) + '\n');
    process.stdout.write('CHAIN-DONE\n');
}

function cli(argv) {
    if (argv[0] === '--child' && argv.length === 2) return child(argv[1]);
    const out = (v) => { process.stdout.write(JSON.stringify(v) + '\n'); process.exitCode = v.ok ? 0 : 1; };
    if (argv.length !== 2 || argv[0] !== '--target' || !isAbsolute(argv[1])) {
        return out({ ok: false, reasons: ['usage: node test/tools/chain-size.mjs --target <abs path>'] });
    }
    return out({ target: argv[1], ...verdict(readChain(argv[1])) });
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await cli(process.argv.slice(2));
