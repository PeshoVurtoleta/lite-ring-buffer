// copyLast inlining-chain gate (M1 SLIM2, ruling Q-M1-GATE A; PLAN TASK 3, ASSERTION A1). Tier: DETERMINISTIC.
// copyLast + lastCheck + rotCopy must stay <= 766 B of bytecode (V8's cumulative-inlining reserve,
// 920 / 1.2) on the pinned Node v26.8.2 / V8 14.6.202.34-node.28, read by test/tools/chain-size.mjs from a
// fresh `--print-bytecode` child. Any other engine FAILS until the pin is moved (fail closed, as ruled).
// Build under test: RB_BUILD (absolute or package-relative) else ../RingBuffer.js. Against the frozen
// a771a79 build (chain 791) the first test fails (expected: the revert check).
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PIN, CHAIN_MAX, parseDump, readChain, verdict } from './tools/chain-size.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = process.env.RB_BUILD
    ? path.resolve(ROOT, process.env.RB_BUILD)
    : path.join(ROOT, 'RingBuffer.js');

const show = (v) => JSON.stringify(v);

// Synthetic dumps: the real header / length line shapes, the pinned engine, the real lengths.
function block(name, len) {
    return '[generated bytecode for function: ' + name + ' (0x1a2b3c4d5e6f <SharedFunctionInfo ' + name + '>)]\n' +
        (len === null ? '' : 'Bytecode length: ' + len + '\n') +
        'Parameter count 7\nRegister count 8\nFrame size 64\n';
}
function dump(blocks, done = true) {
    return blocks.map(([n, l]) => block(n, l)).join('') +
        'CHAIN-ENGINE ' + JSON.stringify({ node: PIN.node, v8: PIN.v8 }) + '\n' + (done ? 'CHAIN-DONE\n' : '');
}
const BASE = [['copyTo', 288], ['copyCheck', 257], ['rotCopy', 192], ['copyLast', 295], ['lastCheck', 278]];

describe('copyLast chain size (pinned engine)', () => {
    it('the live build passes: copyLast + lastCheck + rotCopy <= 766, each in exactly one block', () => {
        const v = verdict(readChain(BUILD));
        assert.equal(v.ok, true, show(v));
        assert.ok(v.chain <= CHAIN_MAX, show(v));
    });

    it('anchor: the copyTo chain (copyTo + copyCheck + rotCopy) reads exactly 737 B', () => {
        const v = verdict(readChain(BUILD));
        assert.equal(v.chainCopyTo, 737, show(v));
    });

    it('padded control: a never-taken branch at lastCheck\'s head reads >= 8 B more and fails', () => {
        const live = verdict(readChain(BUILD));
        const src = readFileSync(BUILD, 'utf8');
        const anchor = 'function lastCheck(rb, data, dst, dstOffset, n, name) {\n';
        assert.equal(src.split(anchor).length, 2, 'lastCheck head anchor must match exactly once');
        const dir = mkdtempSync(path.join(tmpdir(), 'rb-chainsize-'));
        try {
            const padded = path.join(dir, 'RingBuffer.js');
            writeFileSync(padded, src.replace(anchor, anchor +
                '    if (n === -1.5) throw lastArgError(name, dst, n, dstOffset);\n'));
            const v = verdict(readChain(padded));
            assert.ok(v.fns.lastCheck - live.fns.lastCheck >= 8, show({ live: live.fns, padded: v.fns }));
            assert.equal(v.ok, false, show(v));
            assert.ok(v.reasons.some((r) => /^chain \d+ > 766$/.test(r)), show(v.reasons));
        } finally {
            rmSync(dir, { recursive: true, force: true });
        }
    });

    it('an engine that differs from the pin in one field fails (child or parent)', () => {
        const parsed = readChain(BUILD);
        // control on the real child: the pinned engine raises no engine reason (whatever the chain reads)
        const ctl = verdict(parsed, { parent: { ...PIN } });
        assert.equal(ctl.reasons.some((r) => r.includes(' engine ')), false, 'control ' + show(ctl.reasons));
        const v8Off = { node: PIN.node, v8: PIN.v8 + '.1' };
        const nodeOff = { node: 'v26.8.3', v8: PIN.v8 };
        for (const parent of [v8Off, nodeOff]) {
            const v = verdict(parsed, { parent });
            assert.equal(v.ok, false, 'parent ' + show(parent));
            assert.ok(v.reasons.some((r) => r.startsWith('parent engine')), show(v.reasons));
        }
        for (const engine of [v8Off, nodeOff]) {
            const v = verdict({ ...parsed, engine }, { parent: { ...PIN } });
            assert.equal(v.ok, false, 'child ' + show(engine));
            assert.ok(v.reasons.some((r) => r.startsWith('child engine')), show(v.reasons));
        }
    });

    it('synthetic dumps fail closed: missing rotCopy, duplicate copyLast, copyLastFast only, no length line, no DONE, two engine lines', () => {
        const opts = { parent: { ...PIN } };
        const base = verdict(parseDump(dump(BASE)), opts);
        assert.equal(base.ok, true, 'control: the synthetic base passes ' + show(base));
        assert.equal(base.chain, 765, show(base));
        const cases = [
            ['missing rotCopy', dump(BASE.filter(([n]) => n !== 'rotCopy')), /^rotCopy in 0 blocks/],
            ['duplicate copyLast', dump([...BASE, ['copyLast', 295]]), /^copyLast in 2 blocks/],
            ['copyLastFast only', dump(BASE.map(([n, l]) => (n === 'copyLast' ? ['copyLastFast', l] : [n, l]))),
                /^copyLast in 0 blocks/],
            // the next block's length must not be borrowed
            ['no length line', dump([['copyTo', 288], ['copyCheck', 257], ['copyLast', 295], ['lastCheck', null],
                ['rotCopy', 192]]), /^lastCheck has no positive length$/],
            ['no DONE marker', dump(BASE, false), /^no CHAIN-DONE marker$/],
            // two identical pinned engine lines: ambiguous, so no engine is trusted (M1-N1)
            ['two CHAIN-ENGINE lines', dump(BASE).replace('CHAIN-DONE\n', 'CHAIN-ENGINE ' +
                JSON.stringify({ node: PIN.node, v8: PIN.v8 }) + '\nCHAIN-DONE\n'), /^child engine/],
        ];
        for (const [label, txt, re] of cases) {
            const v = verdict(parseDump(txt), opts);
            assert.equal(v.ok, false, label + ' ' + show(v));
            assert.ok(v.reasons.some((r) => re.test(r)), label + ' ' + show(v.reasons));
        }
    });
});
